import "server-only"

import { cacheLife } from "next/cache"

import { isRegulaState, type RegulaState } from "./types"

export type StateEnvelope = {
  state: RegulaState
  /** Where the document came from — shown in the header so it is never ambiguous. */
  origin: "api" | "fixture"
  /** True when the live API failed and we served the committed fixture. */
  degraded: boolean
  /** Set when the API failed; rendered in the degraded banner. */
  error?: string
}

const DEFAULT_API = "http://127.0.0.1:8787"

/** Server-side only. The browser never talks to the API host directly. */
function apiBase(): string {
  return (process.env.REGULA_API_URL ?? process.env.NEXT_PUBLIC_REGULA_API_URL ?? DEFAULT_API).replace(/\/$/, "")
}

const TIMEOUT_MS = 2500

async function readFixture(): Promise<StateEnvelope> {
  // Committed offline fixture generated by `python app/export_mock.py`.
  const fixture = await import("../mock/state.json")
  return {
    state: fixture.default as unknown as RegulaState,
    origin: "fixture",
    degraded: true,
    error: "The Regula API was unreachable, so this page is showing web/mock/state.json.",
  }
}

async function fetchState(): Promise<StateEnvelope> {
  const url = `${apiBase()}/api/state`
  try {
    const response = await fetch(url, {
      cache: "no-store",
      signal: AbortSignal.timeout(TIMEOUT_MS),
      headers: { accept: "application/json" },
    })
    if (!response.ok) throw new Error(`GET /api/state returned ${response.status} ${response.statusText}`)
    const body: unknown = await response.json()
    if (!isRegulaState(body)) {
      throw new Error("GET /api/state did not match the contract (sources/clauses/obligations missing)")
    }
    return { state: body, origin: "api", degraded: false }
  } catch (error) {
    const message = error instanceof Error ? error.message : "unknown error"
    const fallback = await readFixture()
    return {
      ...fallback,
      error: `${message}. Showing web/mock/state.json — regenerate it with python app/export_mock.py.`,
    }
  }
}

/**
 * The dashboard reads exactly one document: `GET /api/state` (contract §"The UI
 * reads exactly one document"). Cached on the `default` profile — the `seconds`
 * profile has an `expire` of one minute, which Cache Components excludes from
 * prerenders and would make the whole app an uncached dynamic route.
 * "Run monitoring" (the next iteration) calls `refresh()` to bust this cache.
 */
export async function getRegulaState(): Promise<StateEnvelope> {
  "use cache"
  cacheLife("default")
  return fetchState()
}
